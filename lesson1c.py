# python datatypes
# 1. Strings- sequence of characters enclosed inside double or single quotes
name="James"
# show output
print(name)

country='Kenya'
# show output
print(country)

# 2.Integers- They are whole numbers.
age=18
# show output
print(age)
students=20
# show output
print(students)
height=2
# show output
print(height)

# 3.Float- numbers with decimal
weight=67.1
# show output
print(weight)
height=1.75
# show output
print(height)

price=100.99
# show output
print(price)